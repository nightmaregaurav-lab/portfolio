import * as z from "zod";

export const schema = z.object({
  summary: z.string().min(1, "Summary is required.").meta({
    title: "Summary",
    description: "A short introduction to the photo collections on the Gallery page.",
  }),
  categories: z.array(
    z.object({
      name: z.string().min(1, "Category name is required.").meta({
        title: "Name",
        description: "The name of a gallery folder.",
      }),
      slugs: z.array(z.object({
        isActive: z.boolean().default(true).meta({
          title: "Is Active",
          description: "Whether this slug is active and should be used to access the category.",
        }),
        slug: z.string().min(1, "Slug is required.").meta({
          title: "Slug",
          description: "A unique URL slug generated from the category name.",
        }),
      }).meta({
        title: "Slug",
        description: "A unique URL slug generated from the category name.",
      })).default([]).meta({
        title: "Slugs",
        description: "The list of slugs including historical ones that can be used to access the category.",
      }),
      coverImage: z.string().optional().meta({
        title: "Cover image URL",
        description: "An optional image to use as this folder's cover.",
      }),
      description: z.string().optional().meta({
        title: "Description",
        description: "Optional introduction shown when this folder is opened.",
      }),
    }).meta({
      title: "Category",
      description: "A named folder in the gallery.",
    }),
  ).default([]).meta({
    title: "Categories",
    description: "The folders used to organize gallery photos. A photo can appear in multiple folders without being copied.",
  }),
  photos: z.array(
    z.object({
      id: z.string().min(1, "ID is required.").meta({
        title: "ID",
        description: "A hidden stable identifier generated by the setup page.",
      }),
      url: z.string().min(1, "Photo URL is required.").meta({
        title: "Photo URL",
        description: "The URL of the photo to display in the gallery.",
      }),
      title: z.string().optional().meta({
        title: "Title",
        description: "An optional title for the photo.",
      }),
      caption: z.string().min(1, "Caption is required.").meta({
        title: "Caption",
        description: "A caption to display with the photo.",
      }),
      categories: z.array(
        z.string().min(1, "Category is required.").meta({
          title: "Category",
          description: "A gallery category that groups this photo.",
        }),
      ).default([]).meta({
        title: "Categories",
        description: "The categories used to group this photo in the gallery.",
      }),
    }).meta({
      title: "Photo",
      description: "A photo and its display information in the gallery.",
    }),
  ).default([]).meta({
    title: "Photos",
    description: "The photos to display in the gallery.",
  }),
}).meta({
  title: "Gallery Configuration",
  description: "Configuration for the portfolio photo gallery.",
});

export type TInput = z.input<typeof schema>;
export type TOutput = z.output<typeof schema>;
export type TModel = TOutput;

export const defaultValues: TInput = {
  summary: "",
  categories: [],
  photos: [],
};
