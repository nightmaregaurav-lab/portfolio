import * as z from "zod";

export const schema = z.object({
  summary: z
    .string()
    .min(1, "Summary is required.")
    .meta({
      title: "Summary",
      description: "A concise introduction shown above the timeline and used as its search result description."
    }),
  milestones: z.array(
    z.object({
      id: z.string().min(1, "ID is required.").meta({
        title: "ID",
        description: "A hidden stable identifier generated by the setup page.",
      }),
      type: z.enum(["Academic", "Professional", "Personal"]).meta({
        title: "Type",
        description: "Choose whether this entry is academic, professional, or personal."
      }),
      title: z.string().min(1, "Title is required.").meta({
        title: "Title",
        description: "The title of the milestone"
      }),
      description: z.string().min(1, "Description is required.").meta({
        title: "Description",
        description: "A brief description of the milestone"
      }),
      start: z.iso.date().min(1, "Start date is required.").meta({
        title: "Start Date",
        description: "When this milestone began."
      }),
      end: z.iso.date().or(z.literal("")).optional().meta({
        title: "End Date",
        description: "When this milestone ended. Leave it empty for ongoing milestones."
      }),
      organisation: z.string().optional().meta({
        title: "Organization",
        description: "The organization associated with the milestone"
      }),
      organizationWebsite: z.string().optional().meta({
        title: "Organization Website",
        description: "The website of the organization associated with the milestone"
      }),
      department: z.string().optional().meta({
        title: "Department",
        description: "The department associated with the milestone"
      }),
      departmentWebsite: z.string().optional().meta({
        title: "Department Website",
        description: "The website of the department associated with the milestone"
      }),
      points: z.array(z.string().min(1, "Point is required.").meta({
        title: "Point",
        description: "A key point or highlight of the milestone"
      })).default([]).meta({
        title: "Points",
        description: "A list of key points or highlights of the milestone"
      }),
      partingNote: z.string().optional().meta({
        title: "Parting Note",
        description: "A final note or message related to the milestone"
      }),
      achievements: z
        .array(
          z.object({
            title: z.string().min(1, "Achievement title is required.").meta({
              title: "Achievement Title",
              description: "The title of the achievement"
            }),
            description: z.string().min(1, "Achievement description is required.").meta({
              title: "Achievement Description",
              description: "A brief description of the achievement"
            }),
            on: z.iso.date().or(z.literal("")).optional().meta({
              title: "Achievement Date",
              description: "The date of the achievement"
            })
          }).meta({
            title: "Achievement",
            description: "An achievement related to the milestone"
          })
        )
        .default([]).meta({
          title: "Achievements",
          description: "A list of achievements related to the milestone"
        })
    }).meta({
      title: "Milestone",
      description: "A significant event in your journey"
    })
  ).default([]).meta({
    title: "Milestones",
    description: "A list of significant events in your journey"
  }),
}).meta({
  title: "Journey Configuration",
  description: "A summary of your journey and the milestones that make it up.",
});

export const buildSchema = schema.extend({
  summary: z.string()
}).partial();

export type TInput = z.input<typeof schema>;
export type TOutput = z.output<typeof schema>;
export type TModel = TOutput;

export const defaultValues: TInput = {
  summary: "",
  milestones: [],
};
