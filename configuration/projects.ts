import * as z from "zod";

export const schema = z.object({
  summary: z.string().min(1, "Summary is required.").meta({
    title: "Summary",
    description: "A concise introduction shown above the project cards and used as the page's search result description.",
  }),
  projects: z.array(
    z.object({
      id: z.string().min(1, "ID is required.").meta({
        title: "ID",
        description: "A hidden stable identifier generated by the setup page.",
      }),
      slugs: z.array(z.object({
        isActive: z.boolean().default(true).meta({
          title: "Is Active",
          description: "Whether this slug is active and should be used to access the project.",
        }),
        slug: z.string().min(1, "Slug is required.").meta({
          title: "Slug",
          description: "A unique URL slug generated from the project title.",
        }),
      })).default([]).meta({
        title: "Slugs",
        description: "The list of slugs including historical ones that can be used to access the project.",
      }),
      title: z.string().min(1, "Title is required.").meta({
        title: "Title",
        description: "The name of the project.",
      }),
      links: z.array(
        z.object({
          name: z.string().min(1, "Link name is required.").meta({
            title: "Name",
            description: "The label for this project link, such as GitHub or a live demo.",
          }),
          url: z.string().min(1, "Link URL is required.").meta({
            title: "URL",
            description: "The address this project link opens.",
          }),
        }).meta({
          title: "Project Link",
          description: "An external link associated with the project.",
        }),
      ).default([]).meta({
        title: "Links",
        description: "External links associated with the project.",
      }),
      description: z.string().min(1, "Description is required.").meta({
        title: "Description",
        description: "A description of the project and what it does.",
      }),
      previewImage: z.string().min(1, "Preview image URL is required.").meta({
        title: "Preview Image",
        description: "A public image URL used as the project's primary card preview. Uploads are not handled here.",
      }),
      images: z.array(z.string().min(1, "Image URL is required.").meta({
        title: "Image URL",
        description: "The URL of an additional project image.",
      })).default([]).meta({
        title: "Images",
        description: "Additional images to show with the project.",
      }),
      keypoints: z.array(
        z.object({
          title: z.string().min(1, "Key point title is required.").meta({
            title: "Title",
            description: "The label for this project detail.",
          }),
          value: z.string().min(1, "Key point value is required.").meta({
            title: "Value",
            description: "The value or short detail for this project.",
          }),
        }).meta({
          title: "Key Point",
          description: "A short detail that highlights an aspect of the project.",
        }),
      ).default([]).meta({
        title: "Key Points",
        description: "A list of short details about the project.",
      }),
      seoKeywords: z.array(z.string().min(1, "SEO keyword is required.").meta({
        title: "Keyword",
        description: "A search keyword associated with the project.",
      })).default([]).meta({
        title: "SEO Keywords",
        description: "Comma-separated search terms describing the project. Use concise words rather than sentences.",
      }),
      milestoneId: z.string().optional().meta({
        title: "Milestone ID",
        description: "Select the existing journey milestone that best explains when or where this project happened.",
      }),
    }).meta({
      title: "Project",
      description: "A project entry displayed on the projects page.",
    }),
  ).default([]).meta({
    title: "Projects",
    description: "The project entries displayed on the projects page.",
  }),
}).meta({
  title: "Projects Configuration",
  description: "Configuration for the projects page and its project entries.",
});

export type TInput = z.input<typeof schema>;
export type TOutput = z.output<typeof schema>;
export type TModel = TOutput;

export const defaultValues: TInput = {
  summary: "",
  projects: [],
};
