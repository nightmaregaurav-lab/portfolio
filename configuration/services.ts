import * as z from "zod";

export const schema = z.object({
  services: z.array(
    z.object({
      id: z.string().min(1, "ID is required.").default("").meta({
        title: "ID",
        description: "A hidden stable identifier generated by the setup page.",
      }),
      title: z.string().min(1, "Title is required.").default("").meta({
        title: "Title",
        description: "The name of the service.",
      }),
      description: z.string().min(1, "Description is required.").default("").meta({
        title: "Description",
        description: "A description of the service provided.",
      }),
      icon: z.string().optional().meta({
        title: "Icon",
        description: "An optional icon to display with the service.",
      }),
      link: z.string().min(1, "Link is required.").default("").meta({
        title: "Link",
        description: "A related URL. Links are automatically detected and made clickable.",
      }),
    }).meta({
      title: "Service",
      description: "A service offered and its related information.",
    }),
  ).default([]).meta({
    title: "Services",
    description: "The list of services offered on the Services page.",
  })
}).meta({
  title: "Services Configuration",
  description: "The configuration for the Services page.",
});

export type TInput = z.input<typeof schema>;
export type TOutput = z.output<typeof schema>;
export type TModel = TOutput;

export const defaultValues: TInput = {
  services: [],
}
